#!/usr/bin/env python3
"""Cross-check the guide against the capture list and write capture/SHOT-LIST.md.

    python check-guide.py

- every ![caption](images/NN-slug.png) in the guide must have an entry in shots.json (same id), and the other way round;
- writes SHOT-LIST.md: one row per shot (id, area, auth, batch, status = captured / pending, caption).
Exit code 1 when the guide and shots.json disagree.
"""
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
DOC = HERE.parent
guide = (DOC / "Gigantic-Prints-Handoff-Guide.md").read_text(encoding="utf-8")
shots = json.loads((HERE / "shots.json").read_text(encoding="utf-8"))["shots"]

refs = re.findall(r"!\[[^\]]*\]\(images/([^)]+)\.png\)", guide)
ids = [s["id"] for s in shots]
missing_in_shots = sorted(set(refs) - set(ids))
unused = sorted(set(ids) - set(refs))
dupes = sorted({i for i in ids if ids.count(i) > 1})

rows = ["| id | auth | viewport | batch | needs | status | caption |", "|---|---|---|---|---|---|---|"]
for s in shots:
    done = (DOC / "images" / (s["id"] + ".png")).is_file()
    rows.append("| `{}` | {} | {} | {} | {} | {} | {} |".format(
        s["id"], s.get("auth", "none"), s.get("viewport", "desktop"), s.get("batch", "now"), s.get("needs", ""),
        "captured" if done else "pending", s.get("caption", "").replace("|", "/")))
n_done = sum(1 for s in shots if (DOC / "images" / (s["id"] + ".png")).is_file())
head = ("# Screenshot list\n\nGenerated by `check-guide.py` from `shots.json`. {} shots, {} captured, {} pending. "
        "`batch now` = final today; `batch b4` = capture in the final run after batch B4.\n\n").format(len(shots), n_done, len(shots) - n_done)
(HERE / "SHOT-LIST.md").write_text(head + "\n".join(rows) + "\n", encoding="utf-8")

print(f"{len(refs)} image references in the guide, {len(ids)} shots, {n_done} captured")
bad = False
if missing_in_shots:
    bad = True
    print("referenced in the guide but not in shots.json:", ", ".join(missing_in_shots))
if unused:
    print("in shots.json but not used in the guide:", ", ".join(unused))
if dupes:
    bad = True
    print("duplicate ids:", ", ".join(dupes))
sys.exit(1 if bad else 0)
